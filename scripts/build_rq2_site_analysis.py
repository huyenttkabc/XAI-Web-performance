"""RQ2: phân tích sai số theo store / tầng / loại trang và Figure 4 (bias theo decile).

Dùng: npm run ml:rq2-sites  (= scripts/build_rq2_site_analysis.py --run=dev-cv-261025-v1.0)
Ghi cạnh run: site-error-analysis.json; và docs/rq2-site-error-analysis.md,
docs/figures/figure-4-bias-by-decile.tex (TikZ, để manuscript \\input). Không fit lại mô hình.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from src.ml.paired_store_tests import pred_column  # noqa: E402
from src.ml.site_error_analysis import bias_by_decile, by_group, per_site_summary  # noqa: E402

TARGETS = {"lh_lcp_ms": "LCP", "tbt_30s_ms": "TBT30"}
MODELS = {("S+R", "random_forest"): "Random Forest S+R", ("S+R", "xgboost"): "XGBoost S+R",
          ("S", "random_forest"): "Random Forest S", ("S", "xgboost"): "XGBoost S"}
FIG_MODELS = [("-", "baseline", "Baseline", "gray", "dashed"), ("S+R", "random_forest", "Random Forest S+R", "black", "solid"),
              ("S+R", "xgboost", "XGBoost S+R", "black!55", "densely dotted")]


def fmt(v):
    """Số ms kiểu Việt: 4.377 (dấu chấm ngăn nghìn)."""
    return f"{v:,.0f}".replace(",", ".")


def figure_tikz(result):
    """Hai panel (LCP, TBT30): x = decile giá trị quan sát, y = trung vị sai số có dấu (giây)."""
    out = ["% Generated by scripts/build_rq2_site_analysis.py — do not edit by hand.",
           "\\begin{tikzpicture}[font=\\sffamily\\scriptsize]"]
    for p, (t, label) in enumerate(TARGETS.items()):
        series = result["bias_by_decile"][t]
        lo = min(min(r["bias_median"] for r in s) for s in series.values())
        hi = max(max(r["bias_median"] for r in s) for s in series.values())
        step = 5000 if t == "lh_lcp_ms" else 1000
        lo, hi = step * (lo // step), step * -(-hi // step)
        x0, w, h = p * 8.0, 6.2, 4.2
        sx = lambda d: x0 + 0.9 + (d - 1) / 9 * (w - 1.2)
        sy = lambda v: (v - lo) / (hi - lo) * h
        out.append(f"\\node[font=\\sffamily\\bfseries\\small, anchor=west] at ({x0},{h + 0.45}) {{{label}}};")
        out.append(f"\\draw ({sx(1) - 0.2:.2f},0) -- ({sx(1) - 0.2:.2f},{h});")
        v = lo
        while v <= hi + 1e-9:
            out.append(f"\\draw ({sx(1) - 0.25:.2f},{sy(v):.2f}) -- ({sx(1) - 0.2:.2f},{sy(v):.2f}) node[left] {{{v / 1000:+.0f}}};")
            v += step
        out.append(f"\\draw[gray!60] ({sx(1) - 0.2:.2f},{sy(0):.2f}) -- ({sx(10) + 0.2:.2f},{sy(0):.2f});")
        for d in range(1, 11):
            out.append(f"\\node at ({sx(d):.2f},-0.25) {{{d}}};")
        out.append(f"\\node at ({(sx(1) + sx(10)) / 2:.2f},-0.65) {{decile of the observed {label}}};")
        out.append(f"\\node[rotate=90] at ({x0 - 0.05:.2f},{h / 2:.2f}) {{median signed error (s)}};")
        for fset, model, name, color, dash in FIG_MODELS:
            pts = series[name]
            path = " -- ".join(f"({sx(r['decile']):.2f},{sy(r['bias_median']):.2f})" for r in pts)
            out.append(f"\\draw[{color}, {dash}, thick] {path};")
            for r in pts:
                out.append(f"\\fill[{color}] ({sx(r['decile']):.2f},{sy(r['bias_median']):.2f}) circle (1.3pt);")
    for i, (_, _, name, color, dash) in enumerate(FIG_MODELS):
        out.append(f"\\draw[{color}, {dash}, thick] ({1.0 + i * 4.2:.2f},-1.25) -- ({1.6 + i * 4.2:.2f},-1.25) node[right, black] {{{name}}};")
    out.append("\\end{tikzpicture}")
    return "\n".join(out)


def report(run, result):
    """Báo cáo Markdown: phân bố MAE theo store, theo tầng, theo loại trang, bias theo decile."""
    L = ["# RQ2 — Phân tích theo site, tầng, loại trang và phân tích sai số", "",
         "> Sinh tự động bởi `scripts/build_rq2_site_analysis.py`. Không sửa tay.",
         f"> Run `{run}` · dự đoán out-of-fold trên store development · lockbox không dùng · không fit lại.", ""]
    for t, label in TARGETS.items():
        L += [f"## {label}", "", "### Phân bố MAE theo store", "",
              "| mô hình | n store | MAE p25 | trung vị | p75 | p90 | % store tốt hơn baseline |", "|---|---|---|---|---|---|---|"]
        for name, s in result["per_site"][t].items():
            L.append(f"| {name} | {s['n_sites']} | {fmt(s['mae_p25'])} | {fmt(s['mae_median'])} | {fmt(s['mae_p75'])} | "
                     f"{fmt(s['mae_p90'])} | {s['share_better_than_baseline'] * 100:.0f}% |")
        for grp, title in (("stratum", "Theo tầng (reference TBT)"), ("page_type", "Theo loại trang")):
            L += ["", f"### {title}", "", "| mô hình | nhóm | n store | MAE | MAE baseline | ΔMAE [CI 95%] |", "|---|---|---|---|---|---|"]
            for name, rows in result[grp][t].items():
                for r in rows:
                    ci = r["delta_mae_ci95"]
                    L.append(f"| {name} | {r['level']} | {r['n_sites']} | {fmt(r['mae'])} | {fmt(r['mae_baseline'])} | "
                             f"{fmt(r['delta_mae'])} [{fmt(ci[0])}; {fmt(ci[1])}] |")
        L += ["", "### Sai số có dấu theo decile giá trị quan sát (dự đoán − thực tế, trung vị, ms)", "",
              "| decile | " + " | ".join(result["bias_by_decile"][t].keys()) + " |", "|---|" + "---|" * len(result["bias_by_decile"][t])]
        names = list(result["bias_by_decile"][t].keys())
        for i in range(len(result["bias_by_decile"][t][names[0]])):
            row = [result["bias_by_decile"][t][n][i] for n in names]
            L.append(f"| {row[0]['decile']} (y ≈ {fmt(row[0]['y_median'])}) | " + " | ".join(fmt(r["bias_median"]) for r in row) + " |")
        L.append("")
    return "\n".join(L)


def main():
    run = next(a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--run="))
    run_dir = ROOT / "data/processed/model-runs" / run
    oof = pd.read_csv(run_dir / "oof-predictions.csv")
    result = {"per_site": {}, "stratum": {}, "page_type": {}, "bias_by_decile": {}}
    for t in TARGETS:
        base = pred_column(t, "-", "baseline")
        result["per_site"][t] = {"Baseline": per_site_summary(oof, t, base, base)}
        for (fset, model), name in MODELS.items():
            col = pred_column(t, fset, model)
            result["per_site"][t][name] = per_site_summary(oof, t, col, base)
        # Chia theo tầng / loại trang chỉ cho 2 mô hình S+R đầu tiên (RF chính, XGBoost kiểm tra độ bền).
        for grp in ("stratum", "page_type"):
            result[grp][t] = {MODELS[k]: by_group(oof, t, pred_column(t, *k), base, grp) for k in list(MODELS)[:2]}
        result["bias_by_decile"][t] = {name: bias_by_decile(oof, t, pred_column(t, fset, model))
                                       for fset, model, name, _, _ in FIG_MODELS}
    (run_dir / "site-error-analysis.json").write_text(json.dumps(result, indent=2))
    (ROOT / "docs/rq2-site-error-analysis.md").write_text(report(run, result), encoding="utf-8")
    (ROOT / "docs/figures/figure-4-bias-by-decile.tex").write_text(figure_tikz(result), encoding="utf-8")
    print("wrote site-error-analysis.json, docs/rq2-site-error-analysis.md, docs/figures/figure-4-bias-by-decile.tex")


if __name__ == "__main__":
    main()
