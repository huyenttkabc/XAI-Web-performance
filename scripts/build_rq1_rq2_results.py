"""Kết quả RQ1/RQ2 từ một run mô hình đã xong (không fit lại; lockbox không bị chạm).

Cách dùng: npm run ml:rq1-rq2 -- --run=dev-cv-261025-v1.0
Ghi cạnh run: paired-store-tests.json; và docs/paired-store-tests-report.md,
docs/figures/figure-3-model-performance.tex (TikZ, để manuscript \\input).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from src.ml.paired_store_tests import MODELS, pred_column, run_all  # noqa: E402

TARGETS = ["lh_lcp_ms", "tbt_30s_ms"]
SETS = ["S", "S+R"]
T_LABEL = {"lh_lcp_ms": "LCP", "tbt_30s_ms": "TBT30"}
M_LABEL = {"baseline": "Baseline", "ridge": "Ridge", "random_forest": "Random Forest", "xgboost": "XGBoost"}


def fmt_p(p):
    return "< 0,001" if p < 0.001 else f"{p:.3f}".replace(".", ",")


def pearson_r(oof):
    """Pearson r của dự đoán out-of-fold (để so với [2], vốn báo cáo r)."""
    return {f"{t}|{s}|{m}": float(np.corrcoef(oof[t], oof[pred_column(t, s, m)])[0, 1])
            for t in TARGETS for s in SETS for m in MODELS[1:]}


def figure_tikz(models):
    """Biểu đồ chấm + râu: MAE kèm CI 95% bootstrap theo site, mỗi target một panel, S rỗng / S+R tô đặc."""
    out = ["% Generated by scripts/build_rq1_rq2_results.py — do not edit by hand.",
           "\\begin{tikzpicture}[font=\\sffamily\\scriptsize]"]
    rows = [("baseline", "-")] + [(m, s) for m in MODELS[1:] for s in SETS]
    for p, t in enumerate(TARGETS):
        recs = {(r["model"], r["feature_set"]): r for r in models if r["target"] == t and not r["shuffled"]}
        step = 2000 if t == "lh_lcp_ms" else 1000  # vạch trục tròn số (ms)
        hi = step * -(-max(recs[k]["mae_ci95"][1] for k in rows) // step)
        x0, w = p * 8.2, 6.0
        sx = lambda v: x0 + 2.2 + v / hi * (w - 2.2)
        out.append(f"\\node[font=\\sffamily\\bfseries\\small, anchor=west] at ({x0},{len(rows) * 0.5 + 0.4}) {{{T_LABEL[t]}}};")
        out.append(f"\\draw ({sx(0):.2f},0) -- ({sx(hi):.2f},0);")
        for k in range(int(hi // step) + 1):
            v = k * step
            out.append(f"\\draw ({sx(v):.2f},0) -- ({sx(v):.2f},-0.08) node[below] {{{v / 1000:.0f}}};")
        out.append(f"\\node at ({(sx(0) + sx(hi)) / 2:.2f},-0.65) {{MAE (s), 95\\% CI}};")
        for i, (m, s) in enumerate(rows):
            y = (len(rows) - i) * 0.5
            r = recs[(m, s)]
            lo, mid, up = r["mae_ci95"][0], r["pooled"]["mae"], r["mae_ci95"][1]
            label = M_LABEL[m] if m == "baseline" else f"{M_LABEL[m]} {s}"
            out.append(f"\\node[anchor=east] at ({x0 + 2.1:.2f},{y:.2f}) {{{label}}};")
            out.append(f"\\draw[gray!40] ({sx(0):.2f},{y:.2f}) -- ({sx(hi):.2f},{y:.2f});")
            out.append(f"\\draw[thick] ({sx(lo):.2f},{y:.2f}) -- ({sx(up):.2f},{y:.2f});")
            style = "fill=black" if s == "S+R" else ("fill=gray" if m == "baseline" else "fill=white")
            out.append(f"\\draw[{style}] ({sx(mid):.2f},{y:.2f}) circle (2.2pt);")
    out.append("\\end{tikzpicture}")
    return "\n".join(out)


def report(run, tests, r_values):
    L = ["# Kiểm định ghép cặp theo store — RQ1/RQ2 (bổ sung cho CI bootstrap)", "",
         "> Sinh tự động bởi `scripts/build_rq1_rq2_results.py`. Không sửa tay.",
         f"> Run `{run}` · đơn vị = store (MAE trung bình các dòng out-of-fold của store) · lockbox không dùng.", "",
         "## 1. Kiểm tra giả định", "",
         "- **Ghép cặp:** mọi mô hình dự đoán cùng các dòng của cùng một store → mỗi store cho một bộ giá trị ghép cặp ✅",
         "- **Độc lập giữa các đơn vị:** store khác nhau, fold theo store; các dòng trong cùng store được gộp thành 1 giá trị ✅",
         "- **Khối đầy đủ (Friedman):** mọi store có giá trị cho mọi mô hình ✅",
         "- **Đối xứng của chênh lệch (Wilcoxon):** xem cột độ lệch (skewness); |skew| > 1 là lệch mạnh → dựa vào sign test (không cần giả định này).", "",
         "## 2. Friedman (4 mô hình, khối = store)", "",
         "| target | bộ | χ² (df) | p (Holm) | hạng TB: baseline / Ridge / RF / XGBoost |", "|---|---|---|---|---|"]
    for f in tests["friedman"]:
        rk = " / ".join(f"{f['mean_rank'][m]:.2f}" for m in MODELS)
        L.append(f"| {T_LABEL[f['target']]} | {f['feature_set']} | {f['chi2']:.1f} ({f['df']}) | {fmt_p(f['p_holm'])} | {rk} |")
    def table(title, rows, label):
        L.extend(["", f"## {title}", "",
                  "| target | so sánh | n store | trung vị Δ (ms) | % store tốt hơn | skew | p Wilcoxon (Holm) | p sign |",
                  "|---|---|---|---|---|---|---|---|"])
        for r in rows:
            L.append(f"| {T_LABEL[r['target']]} | {label(r)} | {r['n_stores']} | {r['median_diff']:,.0f} | "
                     f"{r['share_a_better'] * 100:.0f}% | {r['skewness']:.2f} | {fmt_p(r['p_holm'])} | {fmt_p(r['p_sign'])} |")
    table("3. Mô hình vs baseline (họ 12 phép thử)", tests["vs_baseline"], lambda r: f"{M_LABEL[r['model']]} {r['feature_set']} − baseline")
    table("4. RQ2: S+R vs S cùng mô hình (họ 6 phép thử)", tests["runtime_sr_vs_s"], lambda r: f"{M_LABEL[r['model']]}: S+R − S")
    table("5. G5: Random Forest vs XGBoost, S+R (họ 2 phép thử)", tests["rf_vs_xgb"], lambda r: "RF − XGBoost")
    L.extend(["", "## 6. Pearson r của dự đoán out-of-fold (để so với [2])", "", "| target | bộ | Ridge | RF | XGBoost |", "|---|---|---|---|---|"])
    for t in TARGETS:
        for s in SETS:
            L.append(f"| {T_LABEL[t]} | {s} | " + " | ".join(f"{r_values[f'{t}|{s}|{m}']:.2f}" for m in MODELS[1:]) + " |")
    L.extend(["", "Δ < 0 nghĩa là vế trước có sai số thấp hơn. Kết luận chính vẫn dựa trên CI 95% bootstrap theo store; "
              "p-value chỉ là bằng chứng bổ sung.", ""])
    return "\n".join(L)


def main():
    run = next(a.split("=", 1)[1] for a in sys.argv[1:] if a.startswith("--run="))
    run_dir = ROOT / "data/processed/model-runs" / run
    oof = pd.read_csv(run_dir / "oof-predictions.csv")
    models = json.loads((run_dir / "results.json").read_text())["models"]
    tests = run_all(oof, TARGETS, SETS)
    r_values = pearson_r(oof)
    (run_dir / "paired-store-tests.json").write_text(json.dumps({**tests, "pearson_r": r_values}, indent=2))
    (ROOT / "docs/paired-store-tests-report.md").write_text(report(run, tests, r_values), encoding="utf-8")
    (ROOT / "docs/figures/figure-3-model-performance.tex").write_text(figure_tikz(models), encoding="utf-8")
    print("wrote paired-store-tests.json, docs/paired-store-tests-report.md, docs/figures/figure-3-model-performance.tex")


if __name__ == "__main__":
    main()
