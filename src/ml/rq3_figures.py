import math

from src.ml.explanation_metrics import RANKED_GROUPS

FAULTS = {"lcp-heavy-image": "LCP image", "render-blocking-css": "Render-blocking CSS", "dom-bloat": "DOM size",
          "js-long-task": "First-party long task", "third-party-long-task": "Third-party long task",
          "third-party-scripts": "Third-party scripts"}
TRUTH = {"lcp-heavy-image": "lcp_resource", "render-blocking-css": "render_blocking", "dom-bloat": "dom_layout",
         "js-long-task": "main_thread_js", "third-party-long-task": "third_party", "third-party-scripts": "third_party"}
GROUPS = {"main_thread_js": "Main-thread\\\\JS", "dom_layout": "DOM \\&\\\\layout", "lcp_resource": "LCP\\\\resource",
          "render_blocking": "Render-\\\\blocking", "third_party": "Third\\\\party", "mixed": "Mixed$^{*}$", "server": "Server$^{*}$"}
TARGETS = {"lh_lcp_ms": "LCP", "tbt_30s_ms": "TBT30"}
HEAD = "% Generated by scripts/build_rq3_report.py — do not edit by hand."


def _signed(v):
    return "0.00" if abs(v) < 0.005 else f"{v:+.2f}"


def f2(v):
    return "--" if v is None or v != v else f"{v:.2f}"


def _row(table, target, model):
    return next(r for r in table if (r["split"], r["target"], r["model"]) == ("repetition", target, model)
                and r["variant"] in ("interventional", "model_free"))


def table8_tex(table):
    L = [HEAD, "\\begin{tabular}{@{}llrccccccc@{}}", "\\toprule",
         " & & & \\multicolumn{3}{c}{\\textbf{Random Forest}} & \\multicolumn{2}{c}{\\textbf{XGBoost}} & \\multicolumn{2}{c@{}}{\\textbf{Model-free ref.}} \\\\",
         "\\cmidrule(lr){4-6}\\cmidrule(lr){7-8}\\cmidrule(l){9-10}",
         "\\textbf{Target} & \\textbf{Fault} & $n$ & Hit@1 & Hit@3 & MRR & Hit@1 & MRR & Hit@1 & MRR \\\\", "\\midrule"]
    for t in TARGETS:
        rf, xg, ref = (_row(table, t, m) for m in ("random_forest", "xgboost", "reference"))
        for j, (fault, m) in enumerate(rf["per_fault"].items()):
            x, r = xg["per_fault"][fault], ref["per_fault"][fault]
            L.append(f"{TARGETS[t] if j == 0 else ''} & {FAULTS[fault]} & {m['n']} & {f2(m['hit1'])} & {f2(m['hit3'])} & {f2(m['mrr'])} & "
                     f"{f2(x['hit1'])} & {f2(x['mrr'])} & {f2(r['hit1'])} & {f2(r['mrr'])} \\\\")
        ci = lambda row, k: f"\\makecell{{{f2(row[k])}\\\\[-2pt]{{\\scriptsize[{f2(row['ci95'][k][0])}; {f2(row['ci95'][k][1])}]}}}}"
        L.append(f"\\addlinespace & \\textit{{All}} & {rf['n']} & {ci(rf, 'hit1')} & {f2(rf['hit3'])} & {ci(rf, 'mrr')} & "
                 f"{ci(xg, 'hit1')} & {ci(xg, 'mrr')} & {ci(ref, 'hit1')} & {ci(ref, 'mrr')} \\\\")
        L.append("\\midrule")
    L += ["\\multicolumn{3}{@{}l}{\\textit{Chance (five groups)}} & 0.20 & 0.60 & 0.46 & 0.20 & 0.46 & 0.20 & 0.46 \\\\",
          "\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(L)


def figure5_tikz(profile):
    cols = RANKED_GROUPS + ["mixed", "server"]
    cw, rh, lw = 1.55, 0.5, 3.4
    out = [HEAD, "\\begin{tikzpicture}[font=\\sffamily\\scriptsize]"]
    y = 0.0
    for t, label in TARGETS.items():
        out.append(f"\\node[font=\\sffamily\\bfseries\\small, anchor=west] at (0,{y:.2f}) {{{label}}};")
        y -= 0.75
        for c, g in enumerate(cols):
            out.append(f"\\node[align=center, anchor=south] at ({lw + (c + 0.5) * cw:.2f},{y - 0.05:.2f}) {{{GROUPS[g]}}};")
        y -= 0.1
        for fault in FAULTS:
            if fault not in profile[t]:
                continue
            share = profile[t][fault]["abs_share"]
            y -= rh
            out.append(f"\\node[anchor=east] at ({lw - 0.1:.2f},{y + rh / 2:.2f}) {{{FAULTS[fault]}}};")
            for c, g in enumerate(cols):
                v = share[g]
                x0 = lw + c * cw
                out.append(f"\\fill[black!{min(85, round(85 * v))}] ({x0:.2f},{y:.2f}) rectangle ({x0 + cw:.2f},{y + rh:.2f});")
                out.append(f"\\node[{'white' if v > 0.45 else 'black'}] at ({x0 + cw / 2:.2f},{y + rh / 2:.2f}) {{{100 * v:.0f}\\%}};")
                if g == TRUTH[fault]:
                    out.append(f"\\draw[very thick] ({x0 + 0.03:.2f},{y + 0.03:.2f}) rectangle ({x0 + cw - 0.03:.2f},{y + rh - 0.03:.2f});")
        y -= 0.9
    out += ["\\end{tikzpicture}", ""]
    return "\n".join(out)


def figure6_tikz(cases):
    out = [HEAD, "\\begin{tikzpicture}[font=\\sffamily\\scriptsize]"]
    pw, lw, rh = 4.0, 3.6, 0.34
    for k, c in enumerate(cases):
        ox, oy = (k % 2) * (lw + pw + 1.6), -(k // 2) * 3.7
        steps = [(f["name"].replace("_", "\\_"), f["phi"]) for f in c["features"]] + [("other features", c["rest_phi"])]
        start = math.log1p(c["base_ms"])
        cum = [start]
        for _, p in steps:
            cum.append(cum[-1] + p)
        lo, hi = min(cum), max(cum)
        span = (hi - lo) or 1.0
        sx = lambda v: ox + lw + (v - lo) / span * pw
        title = f"({chr(97 + k)}) {FAULTS[c['fault']]} $\\rightarrow$ {TARGETS[c['target']]}: injected group ranked {c['rank']}"
        out.append(f"\\node[anchor=west, font=\\sffamily\\bfseries\\scriptsize] at ({ox:.2f},{oy:.2f}) {{{title}}};")
        for i, (name, p) in enumerate(steps):
            y = oy - 0.45 - (i + 1) * rh
            a, b = cum[i], cum[i + 1]
            color = "black!75" if p >= 0 else "black!30"
            out.append(f"\\node[anchor=east, font=\\ttfamily\\tiny] at ({ox + lw - 0.1:.2f},{y:.2f}) {{{name}}};")
            out.append(f"\\fill[{color}] ({sx(min(a, b)):.2f},{y - rh * 0.35:.2f}) rectangle ({max(sx(max(a, b)), sx(min(a, b)) + 0.02):.2f},{y + rh * 0.35:.2f});")
            out.append(f"\\node[anchor=west, font=\\tiny] at ({ox + lw + pw + 0.12:.2f},{y:.2f}) {{{_signed(p)}}};")
        ybot = oy - 0.45 - (len(steps) + 0.6) * rh
        for v in (start, cum[-1]):
            out.append(f"\\draw[densely dotted] ({sx(v):.2f},{oy - 0.45:.2f}) -- ({sx(v):.2f},{ybot:.2f});")
        out.append(f"\\node[anchor=north west, font=\\tiny] at ({ox + lw:.2f},{ybot:.2f}) "
                   f"{{$E[f]$ = {c['base_ms']:,.0f} ms; $f(x)$ = {c['pred_ms']:,.0f} ms; observed {c['obs_ms']:,.0f} ms}};")
    out += ["\\end{tikzpicture}", ""]
    return "\n".join(out)
